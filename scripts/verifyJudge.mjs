// **판정만 따로 뺀 순수 함수** — 도구를 도구로 잴 수 있게(U-4 실측 2026-08-29).
//
// **왜 뺐는가.** `verify.mjs` 의 `Test Files` 판정이 `/\x08failed\x08/` 이었다 —
//   파이썬으로 파일을 쓰면서 `\b`(단어 경계)가 **백스페이스 문자**로 박혔다.
//   그 정규식은 **아무것도 매치하지 않는다.** 그래서 `Test Files 8 failed` 인 회차에
//   도구가 **「전항 통과」와 exit 0** 을 냈다. 4차에 지휘부가 잡아낸 그 사고를
//   **막으라고 만든 도구가 같은 방식으로 다시 냈다.**
//
// **잠금이 셋이나 있었는데 셋 다 초록이었다.** `tests/verifyHarness.test.ts` 가
//   *「`Test Files` 줄이 판정에 쓰이는가」* 를 **문자열로** 쟀기 때문이다 —
//   `files &&` 와 `missing.push` 가 한 줄에 있으면 통과였다. **쓰이는 모양은 맞았고 값이 틀렸다.**
//   → `CLAUDE.md` §11 「초록은 대상이 실재한다는 증거가 아니다」의 그 층이다.
//     처방도 같다: **도구에 실물을 먹여 본다.** 아래 함수를 테스트가 직접 호출해
//     실패 줄과 통과 줄을 **둘 다** 넣어 본다(대조군 없는 초록을 만들지 않는다).

/** `Test Files` 요약 한 줄을 받아 실패 사유를 돌려준다. 통과면 `null`. */
export function judgeTestFiles(line) {
  if (!line) return 'vitest Test Files 줄 없음';
  // `failed` 앞뒤로 색코드가 낄 수 있어 단어 경계를 쓰지 않는다 — **부분 일치로 충분하고 안전하다.**
  if (/failed/.test(line)) return `Test Files 에 failed: ${line.trim()}`;
  // `skipped` 는 실패가 아니다(지휘부 2026-09-01) — 의도된 옵트인이고 사유를 따로 적는다.
  return null;
}
