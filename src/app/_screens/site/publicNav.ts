/**
 * 공개 헤더의 **오른쪽 골드 버튼** — 세션에 따라 문구와 목적지가 함께 바뀐다.
 *
 * **왜 두는가.** 4차 F-5 B행에서 최박사가 *"뒤로가기 연타에 로그아웃이 일어난다"* 고 하셨고,
 * 소건 1 이 그 절반(뒤로가기로 닿은 `/login` 화면)을 닫았다. **나머지 절반이 이 버튼**이다 —
 * 로그인한 사람이 현관에 와도 버튼이 여전히 `로그인` 이라고 적혀 있었다.
 * 리다이렉트를 고쳐도 **문구는 그대로 남는다.**
 *
 * **ADR-86 계열** — 버튼 문구와 목적지를 일치시킨다. 그 규율을 공개 현관에 적용한 것이다.
 *
 * ### 왜 `내 홈` 이고 `로그아웃` 이 아닌가 (화면을 보고 정한 근거 셋)
 *
 * ⑴ **자리의 위계.** 이 슬롯(`.site-gnb__login`)은 **골드 면 + 700 굵기**로 헤더에서 가장 강하고
 *    현관의 유일한 상시 CTA 다. 로그아웃은 **나가는** 동작인데 그것을 가장 강한 자리에 두면
 *    돌아온 참여자에게 앱이 권하는 첫 행동이 *나가기* 가 된다.
 *    골드를 전진 동작에만 쓰는 위계는 이미 서 있다(§9.7 #15 `BookPanel` — *골드 primary 금지 ·
 *    세미나 신청 CTA 전용 위계*).
 *
 * ⑵ **증상의 정체.** 문제는 *로그아웃된 것 같다* 였다. 필요한 것은 **로그인 상태임을 알리고
 *    돌아갈 길을 주는 것**이다. `로그아웃` 도 상태를 알리기는 하지만 **제공하는 동작이
 *    사용자가 원하는 것의 정반대**다.
 *
 * ⑶ **로그아웃은 이미 있고 여기엔 없어도 된다.** 어포던스는 멤버 셸의 `LogoutButton` 이다
 *    (시트에 넣지 않은 것도 의도였다 — 폼 액션이라 링크 목록에 섞지 않는다 · `memberSheet.ts`).
 *    `내 홈` 을 누르면 곧바로 그 셸에 닿아 한 번 더 누르면 로그아웃이다.
 *    반대로 현관에 로그아웃을 두면 **같은 동작이 두 곳에 생긴다**(불변식 23).
 *
 * **판정은 순수 함수다** — 부품은 계산하지 않는다(지휘부 강조 ①). 화면이 세션 유무를 넘긴다.
 */
export function publicHeaderAction(signedIn: boolean): PublicNavItem {
  // 문구와 목적지가 **한 객체**다 — 갈라 두면 한쪽만 고치는 날이 온다(그것이 ADR-86 의 사고다).
  return signedIn ? { href: '/home', label: '내 홈' } : { href: '/login', label: '로그인' };
}
