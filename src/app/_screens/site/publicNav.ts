//   메뉴 하나가 늘 때 두 곳이 어긋난다(불변식 23 — 사본이 둘이면 잠금으로 묶는다).
//   화면이 늘어날수록 이 파일 하나만 자란다.
//
// 부품이 아니라 **설정**이다 — 링크 목록일 뿐 렌더도 판정도 하지 않는다.

