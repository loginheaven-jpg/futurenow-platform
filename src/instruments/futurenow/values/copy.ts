//
// **어투는 저장소 실측을 따른다**(3차 검토 N-6). 참여자 표면 전수 집계:
//   `주십시오` 0 · `주세요` 47 · `습니까?` 0. 질문형 53건은 전부 해요체 `~요?`(겠어요·가요·나요·까요).
//   `십시오` 23 건은 전부 동사 직결(적으십시오·고르십시오·정하십시오)이고 `주십시오` 형태는 없다.
//   → 요청은 `~해 주세요`, 강한 요구만 동사 직결 `~십시오`, 질문은 해요체 `~요?`.
//   같은 참여자가 같은 회차에 가치 카드와 갈무리를 연달아 본다. 어투가 갈리면 한 제품으로 읽히지 않는다.
//
// **시점 지시를 쓰지 않는다**(N-7). 2차를 언제 하든 참이어야 한다 —
//   게이트가 없어 1차 직후에 이어서 할 수도 있고(§12-1), 1차 미완료자는 다음 회차로 밀린다(§2-2).
//   문안 원칙 축2 제약: "참·거짓이 회차마다 갈리는 문장을 공통 문구로 넣지 않는다."
//   그래서 `오늘`·`지난 시간`을 쓰지 않고 **대상의 이름을 부른다**(원칙 §2-2).
//
// 금지어: 워크북·진단·설문·평가·점수·지각·미제출·함정. 허락 어휘(괜찮습니다·충분합니다 계열) 0.

