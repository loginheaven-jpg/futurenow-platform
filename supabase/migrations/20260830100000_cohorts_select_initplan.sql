-- `cohorts_select` 정책 — **미인증 가드 + 쿼리당 한 번 평가** (5차 후속 · 둘을 한 파일로)
--
-- **적용 여부는 이 파일이 말하지 않는다** — 정본은 원장이다(지휘부 판정 2026-08-30):
--     select version from supabase_migrations.schema_migrations where version = '20260830100000';
--
-- **검증 결과는 남긴다** — 한 번 일어난 사실이라 얼어야 하는 값이다.
--    ⑴ `anon` `auth.uid()=NULL` · 0행 · 오류 없음 · ⑵ `InitPlan 1` · `loops=1`
--    ⑶ 25 신원 전후 동일(합계 37 → 37 · 불일치 0)
--    롤백 예행이 먼저였고, 되돌리는 문이 옛 정책을 표현식·역할까지 그대로 복원했다.
--
-- **왜 한 파일인가**(지휘부 판정 2026-08-30): 둘이 **같은 정책 한 줄**을 만지고,
--   순서가 강제되며(InitPlan 은 행이 0개여도 평가하므로 가드 없이 적용하면 **지금보다 나빠진다**),
--   중간 상태에 값이 없고, 승인도 한 번으로 끝난다.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- **① 왜 성능 정정이 필요한가 — 내가 적은 근거가 틀렸다.**
--
-- 앞선 마이그레이션(`20260830090000`)에 나는 이렇게 적었다:
--   > `member_state(auth.uid())` 가 행에 의존하지 않으므로 InitPlan 으로 승격해 쿼리당 한 번만 평가한다.
--
-- **틀렸다.** 적용 뒤 `EXPLAIN` 에서 `Filter` 안에 그대로 남았다 — **행마다 돈다.**
-- PostgreSQL 은 `STABLE` 함수 호출을 그 이유만으로 승격하지 않는다(InitPlan 은 **서브쿼리**에 적용된다).
-- **원리로 추정하고 계획을 보지 않은 것이 원인**이고, 지휘부의 *적용 후 EXPLAIN 으로 확인하라* 가 잡았다.
-- 고침은 호출을 **스칼라 서브쿼리로 감싸는 것**이다(Supabase 의 `(select auth.uid())` 관용구와 같은 꼴).
--
-- **② 왜 미인증 가드가 필요한가 — 앞 마이그레이션이 이미 회귀를 만들었다.**
--
-- 정책에 함수 호출을 넣은 순간 미인증 조회가 막혔다. 실측(2026-08-30):
--     role=anon           → ❌ **42501 permission denied for function member_state**
--                            (`anon` 에 EXECUTE 가 REVOKE 돼 있다 · ADR-122)
--     role=authenticated  → **JWT 있으면 정상** · JWT 없으면 22023 'no subject'
--
--   ⚠ **`authenticated` 가 22023 이라고 적은 중간 보고는 잘못 잰 값이다**(지휘부 정정).
--     역할만 바꾸고 **JWT 를 주지 않은** 인위적 조건이었다. **실제 로그인 사용자는 멀쩡하다.**
--     대조군 없이 값 하나만 보고 판단한 그 함정이고, 지휘부의 대조 쌍 권고가 **다음 회차에** 값을 냈다.
--
--   **오류 코드를 정확히 적는다** — anon 은 `42501`(권한)이고 `22023`(no subject)이 아니다.
--   결과는 같아도 원인이 다르다.
--
-- **실해는 없었다**: 미인증이 `cohorts` 를 **직접 SELECT 하는 경로가 없다.**
--   공개 경로는 전부 `SECURITY DEFINER` RPC 이고 DEFINER 는 정책을 타지 않는다 —
--   `resolve_cohort_by_code`·`cohort_seats_taken` 을 `anon` 으로 확인했고 운영 공개 4경로도 200 이다.
--   **그래도 잠재 회귀**라 여기서 닫는다.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- **③ 지휘부의 CASE 안은 통하지 않는다 — 실측으로 확인했다.**
--
-- 지휘부는 단락 평가가 보장되지 않으므로 `CASE` 로 감싸라고 했다. 그 지적(AND·OR 순서가
-- 비용 추정에 따라 바뀐다)은 맞으나, **이 문제는 그것으로 닫히지 않는다.**
--
--   시험 결과(깨끗한 연결 · `auth.uid()` 가 실제로 NULL 인 상태):
--     CASE 가드 (지휘부 안)          anon → ❌ 42501   · authenticated → 1행 · InitPlan ✅
--     TO authenticated (역할 한정)   anon → ✅ 0행     · authenticated → 1행 · InitPlan ✅
--
-- **왜 CASE 로 안 되나**: 함수 EXECUTE 권한은 **실행 시점이 아니라 계획 시점**에 검사된다.
--   `CASE` 가 실행을 건너뛰어도 **함수 이름이 정책에 있는 한** `anon` 은 그 쿼리를 계획조차 못 한다.
--   즉 이것은 *평가 순서* 문제가 아니라 *권한 검사 시점* 문제였다.
--
-- **그래서 정책의 대상 역할을 한정한다.** `TO authenticated` 면 `anon` 은 이 정책을 타지 않고,
--   `anon` 용 정책이 없으므로 **RLS 기본 거부로 빈 결과**가 된다 — **오류가 아니다.**
--   함수 이름이 `anon` 의 계획에 들어가지 않는 것이 요점이다.
--   Supabase 가 정책에 `TO` 를 붙이기를 권고하는 이유와 같다.
--
-- **가드를 이중으로 두지 않는다.** `TO authenticated` 가 이미 미인증을 걸러내므로
--   `auth.uid() IS NOT NULL` 을 안에 또 쓰면 **읽는 사람이 둘 중 어느 것이 방어인지 헷갈린다.**
--   대신 그 사실을 **이 주석이** 문서로 든다.
-- ─────────────────────────────────────────────────────────────────────────────

DROP POLICY IF EXISTS cohorts_select ON public.cohorts;
CREATE POLICY cohorts_select ON public.cohorts FOR SELECT
  -- **미인증은 이 정책을 타지 않는다** → `anon` 용 정책이 없으므로 빈 결과(오류 아님).
  --   이 `TO` 를 지우면 `anon` 이 42501 로 터진다. **지우지 말 것.**
  TO authenticated
  USING (
    -- `is_admin` 은 첫 OR 로 그대로 둔다(운영자 감독이 끊기지 않게).
    --   ⚠ 이 자리는 **절반만 확정됐다** — `20260830090000` §4 의 주 참조.
    --     대상은 확정(누구에게나 걸 수 있다) · **콘솔에서 무엇을 잃는지는 미정**이라 손대지 않았다.
    public.is_admin(auth.uid())
    OR (
      -- **스칼라 서브쿼리로 감싼다** — 이 괄호 하나가 매 행 호출을 InitPlan 으로 바꾼다.
      --   맨 호출로 되돌리면 조용히 느려지고 아무것도 알려주지 않는다.
      (SELECT public.member_state(auth.uid())) <> 'expired'
      AND (coach_id = auth.uid() OR public.is_cohort_member(id, auth.uid()))
    )
  );

