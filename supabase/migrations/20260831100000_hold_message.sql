--   ⑴ **던지는 문장이 실제로 바뀌었다** — 문자열을 눈으로 보지 말고 **띄워서 받는다.**
--        `expired` 인 신원으로 `select public.feed_assert_writable('<uid>')`
--        → `55000` · 메시지가 `이용이 보류되었습니다. 운영자에게 문의해 주십시오.`
