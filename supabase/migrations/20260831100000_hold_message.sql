-- `expired` 안내 문구를 최박사 문구로 — **문안만 바꾼다**
--   (최박사 확정 2026-08-30 · 지휘부 전달)
--
-- **적용 여부는 이 파일이 말하지 않는다** — 정본은 원장이다(지휘부 판정 2026-08-30):
--     select version from supabase_migrations.schema_migrations where version = '20260831100000';
--
-- **검증 결과는 남긴다** — ⑴ `expired` 가 새 문장을 **실제로 던진다**(정의 문자열이 아니라 띄워서 받았다)
--    ⑵ `held` 문장 그대로 · 두 문장이 서로 다름까지 단언한다. 상주 테스트가 통합테스트에 있다.
--
-- **왜 새 파일인가**: 이 문장은 `20260830090000` 안에 있고 **그 파일은 적용됐다.**
--   적용된 마이그레이션은 고치지 않는다(불변식 15) — 변경은 항상 새 파일로.
--
-- **최박사 원문**: *"문구는 이용이 보류되었습니다. 운영자에게 문의해 주십시요 정도면 된다."*
--   구현 문자열은 지휘부가 지정한 형태를 쓴다 — `이용이 보류되었습니다. 운영자에게 문의해 주십시오.`
--   (원문의 `주십시요` 와 한 글자 다르다. **임의로 다듬은 것이 아니라 지휘부 지정값**이고,
--    어긋남 자체는 보고에 적었다. 문안은 **얼어야 하는 값**이라 여기와 화면이 갈리면 안 된다.)
--
-- **사본이 둘이다**(불변식 23). 같은 문장이 두 곳에 산다:
--     ⑴ 여기 — `feed_assert_writable` 이 글쓰기를 막을 때 던지는 문장
--     ⑵ `src/core/membershipVocab.ts` `TIER_LEAD.suspended` — `내 정보` 화면의 설명 줄
--   **둘을 함께 맞췄고**, 화면 쪽은 `membershipVocab.test.ts` 가 글자 그대로 잠근다.
--   여기서 잠그는 것은 `tests/toolGate.test.ts` 다(두 파일이 같은 문장을 들고 있는지).
--
-- **`held` 문장은 건드리지 않는다.** 두 상태는 뜻이 달라 한 문장으로 뭉개면 안 된다 —
--   `held` 는 *확인 중*, `expired` 는 *보류됨* 이다.
--
-- **정본을 읽어 옮겼다**(계열 ⑦): 아래 본문은 `pg_get_functiondef` 로 받은 라이브 정의에서
--   문자열 한 줄만 바꾼 것이다. 초판 기준으로 다시 쓰지 않았다.

CREATE OR REPLACE FUNCTION public.feed_assert_writable(p_uid uuid DEFAULT auth.uid())
RETURNS void LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public AS $$
DECLARE v_state text;
BEGIN
  IF p_uid IS NULL THEN
    RAISE EXCEPTION 'not authenticated' USING errcode = '42501';
  END IF;
  v_state := public.member_state(p_uid);
  IF v_state = 'held' THEN
    RAISE EXCEPTION '계정 확인이 필요해 지금은 글을 올릴 수 없어요. 아래 문의로 알려 주시면 확인해 드릴게요.'
      USING errcode = '55000';
  END IF;
  -- **신설.** 문안을 새로 만들지 않고 `held` 와 가른다 — 두 상태는 뜻이 달라 같은 문장을 쓰면
  --   *확인 중* 과 *보류됨* 이 한 문장으로 뭉개진다.
  --   ↑ 원 주석 그대로다(§3 보존). **바꾼 것은 아래 문자열 하나뿐**이다 — 최박사 확정 2026-08-30.
  IF v_state = 'expired' THEN
    RAISE EXCEPTION '이용이 보류되었습니다. 운영자에게 문의해 주십시오.'
      USING errcode = '55000';
  END IF;
END; $$;

-- ============================================================
-- 되돌리는 문
-- ============================================================
-- 이 파일은 함수 본문의 **문자열 한 줄**만 바꿨다. 되돌리려면 같은 함수를 다시 만들되
--   `expired` 문장을 옛 문안으로 되돌린다:
--       '계정 이용이 보류되었습니다. 문의해 주세요.'
--   나머지(가드 순서 · `held` 문장 · 오류 코드)는 손대지 않았으므로 그대로 둔다.
--
--   ⚠ **화면 사본도 함께 되돌려야 한다** — `src/core/membershipVocab.ts` 의
--     `TIER_LEAD.suspended`. 한쪽만 되돌리면 두 문장이 갈린다(불변식 23).
--
--   **이 절은 잠금이 잡아서 뒤에 더했다** — 처음 쓸 때 빠뜨렸고, `toolGate` 의
--   *되돌리는 법이 있는가* 가 레드를 냈다. 규율이 값을 낸 자리라 그 사실을 남긴다.

