-- 적용 뒤 검증 — 다섯
-- ============================================================
--
--   ⑴ **대조 쌍 — 보류된 운영자 대 보류 안 된 운영자.** [계정]
--        `true` 하나로는 *막혔다* 와 *원래 없다* 를 못 가른다. **같은 사람의 전/후**와
--        **다른 운영자**를 함께 잰다:
--          보류 전 A → is_admin true   · B → true
--          보류 후 A → **false**       · B → **true**(옆 사람은 멀쩡하다)
--          되돌린 뒤 A → true
--        **B 가 끝까지 true 여야** 이 측정이 *운영자 전체가 꺼진 것* 이 아님을 말한다.
--
--   ⑵ **진실표 재검증** — `member_state` 판정이 한 칸도 바뀌지 않아야 한다.
--        `is_admin` 은 **열람 권한 검사**에만 쓰이고 판정 자체를 만들지 않는다.
--        `tests/membership.integration.test.ts` 전량.
--
--   ⑶ **등가 잠금** — 운영자에 대해 `member_state = 'expired'` ⟺ `is_admin = false` 인지.
--        이 등가가 깨지면 만료 산출이 되살아난 것이다(머리말 ⚠ 참조).
--
--   ⑷ **재귀가 없다** — 보류된 운영자로 `member_state` 를 불러 **스택 오버플로가 아니라
--        값이 돌아오는지** 본다. 자기 자신 조회는 `p_uid = auth.uid()` 라 통과해야 한다.
--
--   ⑸ **48개 정책이 실제로 따르는지 표본** — 보류된 운영자가 남의 기수를 못 보는지.
--        `cohorts_select` 는 `is_admin` 이 첫 `OR` 이므로 그것이 꺼지면 뒤가 평가되고,
--        뒤도 `expired` 를 막으므로 **닫힌다.** 자리 넷을 고치지 않고도 닫히는 것이 요점이다.
--
--   **실기수와 실계정은 건드리지 않는다** — 위 [계정] 항목은 테스트 픽스처로 잰다.
