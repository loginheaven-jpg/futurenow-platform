-- **이용 보류는 운영자에게도 전부 적용된다** — `is_admin` 이 보류를 본다
--   (최박사 확정 2026-08-30 · 답은 한 단어였다: *"전부."*)
--
-- ⚠ **이 파일은 아직 적용되지 않았다.**
--
-- ─────────────────────────────────────────────────────────────────────────────
-- **왜 자리 넷이 아니라 여기인가.**
--
-- `expired` 차단을 넣을 때 자리 넷(`feed_can_access`·`feed_assert_writable`·
-- `cohorts_select`·`my_cohorts`)의 첫 `OR` 을 고칠 수도 있었다. **그러면 안 된다.**
--
--   실측(2026-08-30 라이브):
--     `is_admin` 을 쓰는 **정책 48개**(전체 88개 중) · `is_admin` 을 부르는 **함수 27개**
--
--   자리 넷만 고치면 **나머지가 다음 사고의 자리가 된다.** 한 곳을 고치면 48+27 이 함께 따르는
--   자리가 있는데 넷을 골라 고치는 것은, 규칙을 **한 곳**이 아니라 **네 곳**에 두는 일이다
--   (불변식 23 — 사본이 둘이면 잠금으로 묶는다. 여기서는 사본을 만들지 않는 편이 낫다).
--   **지휘부가 42개라 했으나 실측은 48개다** — 세어 보고 적는다.
--
-- **왜 `member_state` 를 부르지 않는가 — 무한 재귀가 된다.**
--
--   `member_state` 는 열람 권한을 함수 안에서 검사하며 **`is_admin` 을 부른다**(ADR-24 패턴):
--       IF p_uid <> auth.uid() AND NOT public.is_admin(auth.uid()) THEN … 42501
--   여기서 `is_admin` 이 다시 `member_state` 를 부르면 **서로가 서로를 부른다.**
--   실물 정의를 읽지 않았으면 그대로 넣었을 자리다(계열 ⑦ — 정본을 먼저 연다).
--
--   그래서 **저장값을 직접 읽는다.** 등가인 이유가 분명하다:
--   `20260830090000` 이후 **`expired` 는 산출되지 않고 운영자가 저장한 경우에만 나온다**
--   (자동 만료 폐지). 즉 `member_state(u) = 'expired'` ⟺ `memberships.status = 'expired'` 다.
--
--   ⚠ **그러므로 이 등가는 「만료를 산출하지 않는다」에 기대고 있다.**
--     누가 만료 산출을 되살리면 이 두 곳이 조용히 갈린다.
--     → 통합테스트가 **두 값이 같은지**를 단언한다(사본 둘을 잠금으로 묶는다 · 불변식 23).
--
-- **왜 막는가**(근거 · 최박사 확정).
--   `이용 보류` 는 **탈퇴에 준하는 처리**다. 보류된 사람이 콘솔에서 남의 갈무리·리포트를
--   계속 본다면 **무엇을 보류한 것인지 말할 수 없다.** 이름과 실제가 어긋난다.
--
-- **실수로 걸었을 때 푸는 길이 있다.**
--   운영자는 **2명**이고 `decide_membership` 이 **자기 자신에게는 걸 수 없게** 막는다
--   (실측: `IF p_user_id = auth.uid() THEN … 42501`). 따라서 한 사람이 걸리면
--   **남은 운영자가 푼다.** 스스로를 잠글 수는 없다.
--
--   ⚠ **다만 둘 다 걸리면 앱으로 풀 길이 없다.** 그 경우의 복구는 이 파일의 되돌리는 문
--     (또는 DB 소유자 권한으로 `memberships` 직접 수정)이다. **알고 두는 위험**이다.
--
-- **성능** — `is_admin` 이 `EXISTS` 둘이 된다. 48개 정책이 부르는 함수이므로 가볍게 유지했다
--   (인덱스 있는 PK 조회 하나가 는다). `member_state` 를 불렀다면 훨씬 무거웠을 것이다.
-- ─────────────────────────────────────────────────────────────────────────────

-- **라이브 정의를 받아 그 위에 얹었다**(`pg_get_functiondef`). 초판 기준으로 다시 쓰지 않았다.
CREATE OR REPLACE FUNCTION public.is_admin(p_user_id uuid)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.users
    WHERE id = p_user_id AND role = 'admin'
  )
  -- **신설** — 이용 보류는 운영자에게도 전부 적용된다(최박사 확정 2026-08-30).
  --   `member_state` 를 부르지 않는 이유는 머리말 참조(상호 재귀).
  AND NOT EXISTS (
    SELECT 1 FROM public.memberships
    WHERE user_id = p_user_id AND status = 'expired'
  );
$$;

